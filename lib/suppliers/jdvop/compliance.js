const FOOD_GROUP_RE = /^预包装食品/;
// 仅针对供应商的政策性限制(不是经营范围问题):自营商品类目提示时忽略
const SUPPLIER_ONLY_GROUP_RE = /^数码整机/;
const NOT_ALLOWED_GROUP = '不在允许上架范围(经营范围外,待变更)';
// 数码电子类目判定:一级为数码/手机通讯,或二/三级为数码配件、电脑外设等(「电脑、办公 > 文具」不算)
const DIGITAL_RE = /数码|手机|电脑|外设|摄影|影音|智能设备|网络产品/;
const isDigitalNames = names => (names || []).some((n, i) => (i === 0 ? /数码|手机/ : DIGITAL_RE).test(n || ''));

function parse(raw) {
  return String(raw == null ? '' : raw).split(/\r?\n/).map(l => l.trim()).filter(Boolean).map(l => {
    const i = l.search(/[::]/); const group = i > 0 ? l.slice(0, i).trim() : l; const kws = (i > 0 ? l.slice(i + 1) : l).split(/[,,、\s]+/).map(s => s.trim()).filter(Boolean);
    return { group, kws };
  });
}
const setting = (k, def) => { const v = require('../../svc').S(k); return v == null ? def : v; };
const blocklist = () => parse(setting('jdvop_blocklist', BLOCKLIST_DEFAULT));
const allowlist = () => parse(setting('jdvop_allowlist', ALLOWLIST_DEFAULT));
function match(list, names, skip) {
  const ns = (names || []).filter(Boolean).map(String), text = ns.join(' / ');
  for (const b of list) { if (skip && skip(b.group)) continue; for (const k of b.kws) {
    if (k[0] === '=' ? (k.length > 1 && ns.includes(k.slice(1))) : text.includes(k)) return { group: b.group, kw: k.replace(/^=/, '') };
  } }
  return null;
}
/** names: 供应商分类名称数组 → 命中的禁售分组 {group, kw} 或 null */
const blockedBy = names => match(blocklist(), names);
/** → 命中的允许分组 {group, kw} 或 null */
const allowedBy = names => match(allowlist(), names);
/**
 * 供应商商品类目审核:先禁售清单,再允许清单。通过返回 null;否则 {group, kw, food?, notAllowed?}
 */
function review(names) {
  const b = blockedBy(names); if (b) return { ...b, food: FOOD_GROUP_RE.test(b.group) };
  if (allowedBy(names)) return null;
  const ns = (names || []).filter(Boolean); return { group: NOT_ALLOWED_GROUP, kw: ns[ns.length - 1] || '', notAllowed: true };
}
/** 允许分组为「食用农产品」→ 鲜活易腐 */
const isFarmProduce = names => { const a = allowedBy(names); return !!a && /农产品/.test(a.group); };
/**
 * 自营商品(后台新增/编辑)类目提示:复用同一套清单,只提示不拦截。
 * 与供应商规则的差别:忽略仅针对供应商的「数码整机」组;数码类(手机通讯/电脑等)视为在范围内。
 */
function scopeWarning(names) {
  const b = match(blocklist(), names, g => SUPPLIER_ONLY_GROUP_RE.test(g));
  if (b) return { ...b, msg: `所选分类疑似不在当前经营范围内(命中「${b.group}」关键词「${b.kw}」)` };
  if (allowedBy(names) || isDigitalNames(names)) return null;
  return { group: NOT_ALLOWED_GROUP, kw: '', msg: '所选分类不在当前允许上架范围(经营范围变更前仅数码、食用农产品可上架)' };
}
// 面向顾客的文案:去掉「京东 / 京东自营 / 京东物流 / 京东配送」等字样(不展示上游渠道)
function stripJd(s) {
  return String(s == null ? '' : s)
    .replace(/感谢您在京东购物[,,。!!]*(欢迎再次光临[。!!]*)?/g, '')
    .replace(/京东(自营|物流|快递|配送|仓|超市|商城|到家|旗舰店|官方)?/g, '')
    .replace(/\bJD\s*(\.com)?\b/gi, '')
    .replace(/[【\[]\s*[】\]]/g, '').replace(/\s{2,}/g, ' ').trim();
}
// 物流轨迹清理:同上,并把「京东【xx营业部】」等改写为中性的「【xx营业部】」
const stripTrace = s => stripJd(s) || '物流状态更新';
